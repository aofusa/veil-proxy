//! Veil: a high-performance reverse proxy and API server library for Linux, built on io_uring, kTLS and rustls
//! (HTTP/1.1, HTTP/2, HTTP/3, gRPC, Proxy-Wasm), with no tokio or monoio on the data plane.
//!
//! The crate is published as **`veil-proxy`** and ships two things: the `veil` proxy binary, and a library
//! for writing API servers. You register ordinary functions as HTTP (or TCP/UDP) handlers and veil's network
//! layer serves them. Only [`api`], [`tokio`](mod@crate::tokio), [`veil_alloc`] and the macros are documented
//! here; the other public modules are internals of the proxy (used by fuzzing, tests and the mesh data plane)
//! and are hidden from this reference.
//!
//! # Depending on veil
//!
//! `veil` on crates.io belongs to another project, so keep the dependency key `veil` (the library is named
//! `veil`, and the code generated by the macros refers to `::veil::`):
//!
//! ```toml
//! [dependencies]
//! veil = { package = "veil-proxy", version = "0.10", default-features = false, features = ["full", "api"] }
//! ```
//!
//! | Feature | Adds |
//! |---------|------|
//! | `handler` | native `Handler` routes, `Request`/`Response`, configuration builder |
//! | `macro` | `#[veil::route]`, `#[veil::main]`, `#[veil::l4_handler]`, `#[derive(veil::Schema)]` |
//! | `openapi` | OpenAPI 3.1 generation, `/openapi.json` and Swagger UI |
//! | `tokio-compat` | tokio-free tokio compatibility layer (`veil::tokio`) |
//! | `l4-handler` | Rust functions as TCP/UDP handlers |
//! | `grpc-handler` | gRPC server with a codec you choose |
//! | `api-core` | all of the above except `tokio-compat`, plus tower `Layer`/`Service` compatibility |
//! | `api` | `api-core` + `tokio-compat` (the default way to use the library) |
//!
//! # Minimal program
//!
//! ```rust,no_run
//! use veil::prelude::*;
//!
//! #[veil::route(path = "/users/{id}", method = "GET")]
//! async fn get_user(id: u64) -> Json<serde_json::Value> {
//!     Json(serde_json::json!({ "id": id }))
//! }
//!
//! #[veil::main]
//! async fn main() -> Result<(), veil::api::Error> {
//!     veil::serve(Config::load()?).await
//! }
//! ```
//!
//! # Memory allocator
//!
//! In library mode (`handler` feature) veil does not define a `#[global_allocator]`; your binary chooses it,
//! for example `#[global_allocator] static A: veil::veil_alloc::VeilAlloc = veil::veil_alloc::VeilAlloc;`
//! (on unix with the `veil-alloc` feature) or mimalloc.
//!
//! # Build requirements
//!
//! Nothing beyond the `Cargo.toml` entry is needed: there is no `.cargo/config.toml` setting to add. On
//! Linux, quiche (HTTP/3) and rustls share one copy of `aws-lc-sys`; building it needs a C compiler, CMake
//! (for `libssl`) and libclang (for bindgen).
//!
//! # Guides
//!
//! See <https://github.com/aofusa/veil-proxy/tree/main/docs/guide> (start with `library.md`).

