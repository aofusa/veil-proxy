class StatusCode(enum.IntEnum):
    """gRPC status codes (grpcio's ``grpc.StatusCode`` is accepted too)."""

    OK = 0
    CANCELLED = 1
    UNKNOWN = 2
    INVALID_ARGUMENT = 3
    DEADLINE_EXCEEDED = 4
    NOT_FOUND = 5
    ALREADY_EXISTS = 6
    PERMISSION_DENIED = 7
    RESOURCE_EXHAUSTED = 8
    FAILED_PRECONDITION = 9
    ABORTED = 10
    OUT_OF_RANGE = 11
    UNIMPLEMENTED = 12
    INTERNAL = 13
    UNAVAILABLE = 14
    DATA_LOSS = 15
    UNAUTHENTICATED = 16


def _code(c):
    """Convert an int, a :class:`StatusCode` or a grpcio ``grpc.StatusCode`` (whose value is ``(int, str)``) to an int."""
    if c is None:
        return 0
    v = getattr(c, "value", c)
    if isinstance(v, tuple):
        v = v[0]
    return int(v)


class _Abort(Exception):
    def __init__(self, code, details):
        super().__init__(details)
        self.code = _code(code)
        self.details = details or ""


_Metadatum = collections.namedtuple("_Metadatum", ["key", "value"])


class ServicerContext:
    """Context of one call (same method names as grpcio's ``ServicerContext``)."""

    def __init__(self, call):
        """Wrap the native call object."""
        self._call = call
        self._code = None
        self._details = ""

    def abort(self, code, details=""):
        """Abort the call with ``code`` and ``details`` (raises)."""
        raise _Abort(code, details)

    def abort_with_status(self, status):
        """Abort the call with a status object that has ``code`` and ``details``."""
        raise _Abort(status.code, getattr(status, "details", ""))

    def set_code(self, code):
        """Set the status code returned when the handler finishes."""
        self._code = code

    def set_details(self, details):
        """Set the status message returned when the handler finishes."""
        self._details = details

    def code(self):
        """Return the status code set so far (``None`` if unset)."""
        return self._code

    def details(self):
        """Return the status message set so far."""
        return self._details

    def invocation_metadata(self):
        """Return the request metadata as a tuple of ``(key, value)`` pairs."""
        return tuple(_Metadatum(k, v) for k, v in self._call.metadata())

    def send_initial_metadata(self, initial_metadata):
        """Add response headers from ``(key, value)`` pairs (before the first response message)."""
        for k, v in initial_metadata:
            self._call.add_header(k, v)

    def set_trailing_metadata(self, trailing_metadata):
        """Set response trailers from ``(key, value)`` pairs."""
        for k, v in trailing_metadata:
            self._call.add_trailer(k, v)

    def time_remaining(self):
        """Return the seconds left until the deadline, or ``None`` if there is none."""
        return self._call.time_remaining()

    def is_active(self):
        """Return False once the client has cancelled or disconnected."""
        return self._call.is_active()

    def peer(self):
        """Return the peer address (always an empty string for now)."""
        return ""

    def method(self):
        """Return the full method path, e.g. ``/pkg.Svc/Method``."""
        return self._call.method()


class _RequestIterator:
    def __init__(self, call, des):
        self._call = call
        self._des = des

    def __iter__(self):
        return self

    def __next__(self):
        b = _recv(self._call)
        if b is None:
            raise StopIteration
        return self._des(b)


def _recv(call):
    try:
        return call.recv()
    except RuntimeError as e:
        if len(e.args) == 2 and isinstance(e.args[0], int):
            raise _Abort(e.args[0], e.args[1])
        raise


def _identity(x):
    return x


class _Method:
    """One registered method (Rust calls ``handle(call) -> (code, message)``)."""

    def __init__(self, behavior, request_streaming, response_streaming, deserializer, serializer):
        self.behavior = behavior
        self.request_streaming = request_streaming
        self.response_streaming = response_streaming
        self.des = deserializer or _identity
        self.ser = serializer or _identity

    def handle(self, call):
        ctx = ServicerContext(call)
        try:
            if self.request_streaming:
                request = _RequestIterator(call, self.des)
            else:
                first = _recv(call)
                if first is None:
                    return (13, "missing request message")
                if _recv(call) is not None:
                    return (13, "unary call received more than one request message")
                request = self.des(first)
            result = self.behavior(request, ctx)
            if inspect.iscoroutine(result):
                result = _run_coro(result)
            if self.response_streaming:
                it = _aiter_sync(result) if hasattr(result, "__aiter__") else iter(result)
                for m in it:
                    if not call.send(self.ser(m)):
                        close = getattr(it, "close", None)
                        if close:
                            close()
                        return (1, "cancelled")
            else:
                if result is None:
                    if _code(ctx._code) != 0:
                        return (_code(ctx._code), ctx._details)
                    return (13, "no response message")
                if _code(ctx._code) in (0,) or ctx._code is None:
                    call.send(self.ser(result))
            return (_code(ctx._code), ctx._details if _code(ctx._code) != 0 else "")
        except _Abort as a:
            return (a.code, a.details)
        except Exception as e:  # grpcio と同じく UNKNOWN
            traceback.print_exc()
            return (2, "Exception calling application: %s" % e)


def _register(app, path, behavior, req_s, resp_s, des, ser):
    app = app or _default_app
    app.grpc_methods.append((path, _Method(behavior, req_s, resp_s, des, ser)))
    # F-265: protoc の生成した型（FromString / SerializeToString）なら、その .proto を OpenAPI の型に使う
    for f in (des, ser):
        fd = _file_of(f)
        if fd is not None:
            _add_file(app, fd)


def _file_of(func):
    """The ``FileDescriptor`` of a protoc-generated message class whose bound method is ``func``, if any."""
    owner = getattr(func, "__self__", None)
    desc = getattr(owner, "DESCRIPTOR", None)
    return getattr(desc, "file", None)


def _varint(n):
    out = bytearray()
    while n >= 0x80:
        out.append((n & 0x7F) | 0x80)
        n >>= 7
    out.append(n)
    return bytes(out)


def _add_file(app, file_descriptor):
    """Add ``file_descriptor`` and the files it imports as a ``FileDescriptorSet`` (once per file)."""
    seen = getattr(app, "_grpc_descriptor_files", None)
    if seen is None:
        seen = app._grpc_descriptor_files = set()
    out = bytearray()
    todo = [file_descriptor]
    while todo:
        fd = todo.pop()
        if fd.name in seen:
            continue
        seen.add(fd.name)
        raw = fd.serialized_pb
        out += b"\x0a" + _varint(len(raw)) + raw  # FileDescriptorSet.file (field 1)
        todo.extend(getattr(fd, "dependencies", ()))
    if out:
        app.grpc_descriptors.append(bytes(out))


def add_descriptor(descriptor, app=None):
    """Use the types of a ``.proto`` file in the OpenAPI document of the gRPC methods.

    ``descriptor`` is the ``DESCRIPTOR`` of a ``*_pb2`` module (a ``FileDescriptor``; the files it imports are
    included) or the bytes of a serialized ``FileDescriptorSet``. Methods registered through :class:`Server`
    or with protoc-generated serializers find their types without this call.
    """
    app = app or _default_app
    if isinstance(descriptor, (bytes, bytearray, memoryview)):
        app.grpc_descriptors.append(bytes(descriptor))
    else:
        _add_file(app, descriptor)


def _decorator(req_s, resp_s):
    def make(path, request_deserializer=None, response_serializer=None, app=None):
        def deco(func):
            _register(app, path, func, req_s, resp_s, request_deserializer, response_serializer)
            return func

        return deco

    return make


unary_unary = _decorator(False, False)
unary_stream = _decorator(False, True)
stream_unary = _decorator(True, False)
stream_stream = _decorator(True, True)
unary_unary.__doc__ = "Unary-unary: one request, one response. ``func(request, context) -> response``."
unary_stream.__doc__ = "Server streaming. ``func(request, context)`` returns an iterator or generator of responses."
stream_unary.__doc__ = "Client streaming. ``func(request_iterator, context) -> response``."
stream_stream.__doc__ = "Bidirectional streaming. ``func(request_iterator, context)`` returns an iterator of responses."


def add_health(app=None):
    """Register ``grpc.health.v1.Health`` (Check and Watch; the whole server reports SERVING)."""
    (app or _default_app).grpc_health = True


class Server:
    """A stand-in for ``grpc.Server`` to pass to the generated ``add_<Service>Servicer_to_server``.

    Methods are registered on a veil ``App`` (default: the module-level app) and the server is started with
    ``start()`` / ``wait_for_termination()`` or ``app.run(...)``.
    """

    def __init__(self, app=None):
        """Create a server bound to ``app`` (default: the module-level app)."""
        self.app = app or _default_app
        self._listen = None
        self._kw = {}

    def add_generic_rpc_handlers(self, generic_rpc_handlers):
        """Register the handlers produced by ``grpc.method_handlers_generic_handler``."""
        for h in generic_rpc_handlers:
            handlers = getattr(h, "_method_handlers", None)
            if handlers is None:
                raise TypeError(
                    "veil.grpc.Server supports handlers made by grpc.method_handlers_generic_handler "
                    "(the code generated by grpc_tools.protoc)"
                )
            for path, rpc in handlers.items():
                self._add(path, rpc)

    def add_registered_method_handlers(self, service_name, method_handlers):
        """Register the method handlers of ``service_name`` (newer grpcio-tools output)."""
        for name, rpc in method_handlers.items():
            self._add("/%s/%s" % (service_name, name), rpc)

    def _add(self, path, rpc):
        # 新しい grpcio-tools の生成コードは add_generic_rpc_handlers と add_registered_method_handlers の
        # 両方を呼ぶので、同じメソッドは 1 回だけ登録する
        if any(p == path for p, _ in self.app.grpc_methods):
            return
        req_s, resp_s = bool(rpc.request_streaming), bool(rpc.response_streaming)
        behavior = (
            rpc.stream_stream
            if req_s and resp_s
            else rpc.stream_unary if req_s else rpc.unary_stream if resp_s else rpc.unary_unary
        )
        _register(self.app, path, behavior, req_s, resp_s, rpc.request_deserializer, rpc.response_serializer)

    def add_insecure_port(self, address):
        """Set the plaintext (h2c) address to listen on (``[::]:50051`` is accepted) and return its port."""
        self._listen = address.replace("[::]", "0.0.0.0")
        return int(address.rsplit(":", 1)[1])

    def add_secure_port(self, address, server_credentials=None):
        """Not supported; use ``app.run(listen=..., tls_cert=..., tls_key=...)`` for TLS."""
        raise NotImplementedError(
            "use app.run(listen=..., tls_cert=..., tls_key=...) for TLS (HTTP/2 and HTTP/3)"
        )

    def start(self):
        """Does nothing; the server is started by :meth:`wait_for_termination`."""
        pass

    def wait_for_termination(self, timeout=None, **kw):
        """Start the server and block until it stops (same as ``veil.run``)."""
        kw = dict(self._kw, **kw)
        if self._listen and "listen_cleartext" not in kw:
            kw["listen_cleartext"] = self._listen
        self.app.run(**kw)

    def stop(self, grace=None):
        """Stop the running server gracefully."""
        from . import shutdown

        shutdown()
