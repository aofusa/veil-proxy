"""Write gRPC servers in Python with veil.

There are two layers. In both, message (de)serialisation is done by a library of your choice (protobuf,
betterproto, JSON, ...); veil itself does not depend on protobuf.

**Plain layer (no dependency)**:

.. code-block:: python

    import veil, veil.grpc
    from demo_pb2 import HelloRequest, HelloReply

    @veil.grpc.unary_unary("/demo.v1.Demo/SayHello",
                           request_deserializer=HelloRequest.FromString,
                           response_serializer=HelloReply.SerializeToString)
    def say_hello(request, context):
        return HelloReply(message="Hello " + request.name)

    veil.run(listen_cleartext="127.0.0.1:50051")

Without ``request_deserializer`` / ``response_serializer`` messages are passed as ``bytes``.
``unary_stream``, ``stream_unary`` and ``stream_stream`` work the same way (streaming input is an
iterator, streaming output an iterator or generator). ``async def`` and async generators are supported.

**grpcio layer** (``pip install veil-api[grpc]``): pass a :class:`Server` to the
``add_<Service>Servicer_to_server(servicer, server)`` function generated by ``grpc_tools.protoc``:

.. code-block:: python

    server = veil.grpc.Server()
    demo_pb2_grpc.add_DemoServicer_to_server(MyServicer(), server)
    server.add_insecure_port("127.0.0.1:50051")
    server.start(); server.wait_for_termination()

``context`` provides the main parts of grpcio's ``ServicerContext`` (``abort``, ``set_code``,
``set_details``, ``invocation_metadata``, ``send_initial_metadata``, ``set_trailing_metadata``,
``time_remaining``, ``is_active``, ``peer``).
"""

